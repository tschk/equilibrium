//! Synthesize a C header from a source file's exported functions, for languages whose compiler
//! does not write a usable one. Each language contributes a thin scanner that finds exported
//! functions and a type map from its spelling of a type to a C type; this module does the rest
//! (grouped parameters, pointers, rendering, and reporting what could not be mapped).

use crate::c_header::{parse_function_line, split_top_level_commas, strip_c_comments};
use crate::detector::Language;

/// An exported function as the source language spells it.
pub(crate) struct ForeignFn {
    /// The C symbol name.
    pub(crate) symbol: String,
    /// `(name, type)` in source spelling.
    pub(crate) params: Vec<(String, String)>,
    /// `None` means the function returns nothing (`void`).
    pub(crate) ret: Option<String>,
}

pub(crate) struct Synthesized {
    pub(crate) header: String,
    pub(crate) warnings: Vec<String>,
}

/// A language's mapping from its type spelling to a C type, or `None` when it has no C equivalent.
type TypeMap = fn(&str) -> Option<String>;

/// Build a header for `source` written in `language`, or `None` when this language has no
/// source scanner or the source exports nothing that could be bound.
pub(crate) fn synthesize(language: Language, source: &str) -> Option<Synthesized> {
    let (functions, map, prelude): (Vec<ForeignFn>, TypeMap, String) = match language {
        Language::C => (c_functions(source), c_type, c_type_declarations(source)),
        Language::Cpp => (c_functions(&extern_c_items(source)), c_type, String::new()),
        Language::Nim => (nim_functions(source), nim_type, String::new()),
        Language::Rust => (rust_functions(source), rust_type, String::new()),
        Language::Zig => (zig_functions(source), zig_type, String::new()),
        Language::Odin => (odin_functions(source), odin_type, String::new()),
        Language::V => (v_functions(source), v_type, String::new()),
        _ => return None,
    };
    render(language, functions, map, &prelude)
}

fn render(
    language: Language,
    functions: Vec<ForeignFn>,
    map: TypeMap,
    prelude: &str,
) -> Option<Synthesized> {
    let mut warnings = Vec::new();
    let mut prototypes = Vec::new();
    'functions: for function in functions {
        let ret = match &function.ret {
            None => "void".to_string(),
            Some(ty) => match map(ty) {
                Some(c) => c,
                None => {
                    warnings.push(unmapped(language, &function.symbol, "return", ty));
                    continue;
                }
            },
        };
        let mut params = Vec::new();
        for (name, ty) in &function.params {
            match map(ty) {
                Some(c) if c != "void" => params.push(format!("{c} {name}")),
                _ => {
                    warnings.push(unmapped(language, &function.symbol, "parameter", ty));
                    continue 'functions;
                }
            }
        }
        let params = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        prototypes.push(format!("{ret} {}({params});", function.symbol));
    }
    if prototypes.is_empty() {
        return None;
    }
    let mut header = format!(
        "/* Generated by equilibrium-ffi from {language:?} source exports. */\n\
         #pragma once\n#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n"
    );
    if !prelude.trim().is_empty() {
        header.push_str(prelude.trim());
        header.push_str("\n\n");
    }
    for prototype in prototypes {
        header.push_str(&prototype);
        header.push('\n');
    }
    Some(Synthesized { header, warnings })
}

fn unmapped(language: Language, symbol: &str, what: &str, ty: &str) -> String {
    format!("Skipped export {symbol}: {language:?} {what} type `{ty}` has no C equivalent")
}

/// Resolve grouped parameters (`a, b: cint` in Nim/Odin, `a, b int` in V): a name without its own
/// type takes the type of the next parameter that has one.
pub(crate) fn resolve_grouped(
    items: Vec<(String, Option<String>)>,
) -> Option<Vec<(String, String)>> {
    let mut out = Vec::with_capacity(items.len());
    let mut pending = Vec::new();
    for (name, ty) in items {
        match ty {
            None => pending.push(name),
            Some(ty) => {
                for name in pending.drain(..) {
                    out.push((name, ty.clone()));
                }
                out.push((name, ty));
            }
        }
    }
    pending.is_empty().then_some(out)
}

/// `T *` / `const T *` for a pointee already mapped to C.
pub(crate) fn pointer_to(pointee: &str, is_const: bool) -> String {
    if is_const {
        format!("const {pointee} *")
    } else {
        format!("{pointee} *")
    }
}

// ── C ──────────────────────────────────────────────────────────────────────

/// C types are already C; the binding generator reports any it cannot map.
fn c_type(ty: &str) -> Option<String> {
    Some(ty.to_string())
}

/// Split C source into its top-level items: `(head, body)` where `head` is the text before a
/// depth-0 `{` (or the whole `;`-terminated item) and `body` is the braced block, if any.
/// Preprocessor lines are dropped; callers that need them read them separately.
fn top_level_items(source: &str) -> Vec<(String, Option<String>)> {
    let text: String = strip_c_comments(source)
        .lines()
        .filter(|line| !line.trim_start().starts_with('#'))
        .collect::<Vec<_>>()
        .join("\n");
    let mut items = Vec::new();
    let mut depth = 0usize;
    let mut head = String::new();
    let mut body = String::new();
    for ch in text.chars() {
        match ch {
            '{' => {
                if depth > 0 {
                    body.push(ch);
                }
                depth += 1;
            }
            '}' => {
                depth = depth.saturating_sub(1);
                if depth > 0 {
                    body.push(ch);
                } else {
                    items.push((head.trim().to_string(), Some(std::mem::take(&mut body))));
                    head.clear();
                }
            }
            ';' if depth == 0 => {
                let item = head.trim().to_string();
                head.clear();
                // `typedef struct {..} T;` — the name after `}` belongs to the previous item.
                if let Some((prev_head, Some(_))) = items.last_mut() {
                    if prev_head.starts_with("typedef") || is_aggregate(prev_head) {
                        prev_head.push_str(" } ");
                        prev_head.push_str(&item);
                        continue;
                    }
                }
                if !item.is_empty() {
                    items.push((item, None));
                }
            }
            _ if depth > 0 => body.push(ch),
            _ => head.push(ch),
        }
    }
    items
}

fn is_aggregate(head: &str) -> bool {
    ["struct", "union", "enum"]
        .iter()
        .any(|kw| head.split_whitespace().next() == Some(kw))
}

/// Non-`static` function definitions, as prototypes. `main` is never part of a library ABI.
fn c_functions(source: &str) -> Vec<ForeignFn> {
    top_level_items(source)
        .into_iter()
        .filter_map(|(head, body)| {
            body?;
            let words: Vec<&str> = head.split_whitespace().collect();
            if words.contains(&"static") || words.first() == Some(&"typedef") || is_aggregate(&head)
            {
                return None;
            }
            if !head.contains('(') || head.contains('=') {
                return None;
            }
            let head = head.replace("inline ", "").replace("extern ", "");
            let def = parse_function_line(&format!("{} ;", head.trim()))?;
            (def.name != "main").then(|| ForeignFn {
                symbol: def.name,
                params: def
                    .params
                    .into_iter()
                    .map(|(ty, name)| (name, ty))
                    .collect(),
                ret: (def.return_type.trim() != "void").then_some(def.return_type),
            })
        })
        .collect()
}

/// The type declarations a prototype may reference: top-level typedefs, aggregates and enums,
/// copied verbatim, plus `#include <...>` and object-like `#define`s.
fn c_type_declarations(source: &str) -> String {
    let mut out = Vec::new();
    for line in strip_c_comments(source).lines() {
        let line = line.trim();
        let directive = line.trim_start_matches('#').trim_start();
        if line.starts_with('#')
            && (directive.starts_with("include <")
                || (directive.starts_with("define ")
                    && !directive["define ".len()..]
                        .split_whitespace()
                        .next()
                        .is_some_and(|name| name.contains('('))))
        {
            out.push(line.to_string());
        }
    }
    for (head, body) in top_level_items(source) {
        let typedef = head.starts_with("typedef");
        if !typedef && !is_aggregate(&head) {
            continue;
        }
        match body {
            // `typedef struct P {` + body + ` } P` were stitched into `head` as "<open> } <name>".
            Some(body) => match head.split_once(" } ") {
                Some((open, name)) => out.push(format!("{open} {{{body}}} {name};")),
                None if !head.contains('(') => out.push(format!("{head} {{{body}}};")),
                None => {}
            },
            None => out.push(format!("{head};")),
        }
    }
    out.join("\n")
}

// ── C++ ────────────────────────────────────────────────────────────────────

/// The `extern "C"` part of a C++ source, as C: the contents of `extern "C" { … }` blocks and
/// each `extern "C" <definition>`. Everything else is C++ and has no C ABI.
fn extern_c_items(source: &str) -> String {
    let text = strip_c_comments(source);
    let mut out = String::new();
    let mut rest = text.as_str();
    while let Some(at) = rest.find("extern \"C\"") {
        rest = rest[at + "extern \"C\"".len()..].trim_start();
        let block = rest.starts_with('{');
        let start = usize::from(block);
        let mut depth = 0usize;
        let mut end = rest.len();
        for (index, ch) in rest.char_indices().skip(start) {
            match ch {
                '{' => depth += 1,
                '}' if depth == 0 && block => {
                    end = index;
                    break;
                }
                '}' => {
                    depth -= 1;
                    if depth == 0 && !block {
                        end = index + 1;
                        break;
                    }
                }
                ';' if depth == 0 && !block => {
                    end = index + 1;
                    break;
                }
                _ => {}
            }
        }
        out.push_str(&rest[start..end]);
        out.push('\n');
        rest = &rest[(end + usize::from(block)).min(rest.len())..];
    }
    out
}

// ── D ──────────────────────────────────────────────────────────────────────

/// Turn the C++ header `ldc2`/`dmd -HC` writes into C: `extern "C"` prototypes lose the linkage
/// prefix, and `struct S final { … }` keeps only its data members. Other C++ (`extern(C++)`
/// declarations, templates) is dropped. `None` when nothing `extern "C"` was declared.
pub(crate) fn d_header_from_hc(hc: &str) -> Option<String> {
    let mut includes = Vec::new();
    let mut structs = Vec::new();
    let mut prototypes = Vec::new();
    let mut lines = hc.lines().map(str::trim);
    while let Some(line) = lines.next() {
        if line.starts_with("#include <") {
            includes.push(line.to_string());
        } else if let Some(proto) = line.strip_prefix("extern \"C\" ") {
            prototypes.push(proto.replace("()", "(void)"));
        } else if let Some(name) = line
            .strip_prefix("struct ")
            .and_then(|rest| rest.strip_suffix(" final").or(Some(rest)))
            .filter(|name| crate::c_header::is_c_identifier(name))
        {
            // Members are `type name;` lines at the struct's own brace level.
            let mut depth = 0usize;
            let mut fields = Vec::new();
            for line in lines.by_ref() {
                depth += line.matches('{').count();
                depth = depth.saturating_sub(line.matches('}').count());
                if depth == 1 && line.ends_with(';') && !line.contains('(') {
                    fields.push(format!("    {line}"));
                }
                if depth == 0 && line.contains('}') {
                    break;
                }
            }
            structs.push(format!(
                "typedef struct {name} {{\n{}\n}} {name};",
                fields.join("\n")
            ));
        }
    }
    if prototypes.is_empty() {
        return None;
    }
    Some(format!(
        "/* Generated by equilibrium-ffi from the D compiler's -HC header. */\n#pragma once\n\
         #include <stdbool.h>\n{}\n\n{}\n\n{}\n",
        includes.join("\n"),
        structs.join("\n\n"),
        prototypes.join("\n")
    ))
}

/// Collect a declaration that starts at `lines[start]` and may continue over following lines,
/// until `stop` is seen outside brackets. Returns the text before `stop`.
fn signature_text(lines: &[&str], start: usize, stop: char) -> String {
    let mut depth = 0i32;
    let mut text = String::new();
    for line in &lines[start..] {
        for ch in line.chars() {
            match ch {
                c if c == stop && depth == 0 => return text,
                '(' | '[' | '{' => depth += 1,
                ')' | ']' | '}' => depth -= 1,
                _ => {}
            }
            text.push(ch);
        }
        text.push(' ');
    }
    text
}

/// `name: type` items (or bare names, for grouped parameters) separated by `separators`.
fn named_params(list: &str, separators: &[char], sep: &str) -> Option<Vec<(String, String)>> {
    let mut items = Vec::new();
    for group in split_top_level_commas(&list.replace(separators, ",")) {
        let group = group.trim();
        if group.is_empty() {
            continue;
        }
        let group = group.split_once('=').map_or(group, |(head, _)| head).trim();
        match group.split_once(sep) {
            Some((name, ty)) => items.push((name.trim().to_string(), Some(ty.trim().to_string()))),
            None => items.push((group.to_string(), None)),
        }
    }
    resolve_grouped(items)
}

/// Text between the first `(` and its matching `)`, and what follows it.
fn parenthesized(text: &str) -> Option<(&str, &str)> {
    let open = text.find('(')?;
    let mut depth = 0usize;
    for (index, ch) in text[open..].char_indices() {
        match ch {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 {
                    let close = open + index;
                    return Some((&text[open + 1..close], &text[close + 1..]));
                }
            }
            _ => {}
        }
    }
    None
}

// ── Nim ────────────────────────────────────────────────────────────────────

/// `proc name*(a, b: cint): cint {.exportc, cdecl.} =` — only `exportc` procs have an unmangled
/// symbol; `exportc: "other"` renames it.
fn nim_functions(source: &str) -> Vec<ForeignFn> {
    let lines: Vec<&str> = source.lines().collect();
    let mut out = Vec::new();
    for (index, line) in lines.iter().enumerate() {
        let trimmed = line.trim_start();
        let Some(rest) = trimmed
            .strip_prefix("proc ")
            .or_else(|| trimmed.strip_prefix("func "))
        else {
            continue;
        };
        let text = signature_text(&lines, index, '=');
        let Some(pragma) = text.find("{.").map(|at| &text[at..]) else {
            continue;
        };
        if !pragma.contains("exportc") {
            continue;
        }
        let name_end = rest
            .find(|c: char| !(c.is_alphanumeric() || c == '_'))
            .unwrap_or(rest.len());
        let symbol = pragma
            .split_once("exportc")
            .and_then(|(_, after)| after.trim_start().strip_prefix(':'))
            .and_then(|after| after.split('"').nth(1))
            .map_or_else(|| rest[..name_end].to_string(), str::to_string);
        let Some((params, after)) = parenthesized(&text) else {
            continue;
        };
        let ret = after
            .split("{.")
            .next()
            .and_then(|head| head.trim().strip_prefix(':'))
            .map(|ty| ty.trim().to_string())
            .filter(|ty| !ty.is_empty() && ty != "void");
        if let Some(params) = named_params(params, &[';'], ":") {
            out.push(ForeignFn {
                symbol,
                params,
                ret,
            });
        }
    }
    out
}

fn nim_type(ty: &str) -> Option<String> {
    let ty = ty.trim();
    if let Some(inner) = ty.strip_prefix("ptr ").or_else(|| ty.strip_prefix("var ")) {
        return nim_type(inner).map(|c| pointer_to(&c, false));
    }
    Some(
        match ty {
            "cint" => "int",
            "cuint" => "unsigned int",
            "clong" => "long",
            "culong" => "unsigned long",
            "clonglong" => "long long",
            "culonglong" => "unsigned long long",
            "cshort" => "short",
            "cushort" => "unsigned short",
            "cchar" | "char" => "char",
            "cschar" => "signed char",
            "cuchar" | "byte" => "unsigned char",
            "cfloat" | "float32" => "float",
            "cdouble" | "float64" | "float" => "double",
            "csize_t" => "size_t",
            "int8" => "int8_t",
            "int16" => "int16_t",
            "int32" => "int32_t",
            "int64" => "int64_t",
            "uint8" => "uint8_t",
            "uint16" => "uint16_t",
            "uint32" => "uint32_t",
            "uint64" => "uint64_t",
            "int" => "intptr_t",
            "uint" => "uintptr_t",
            "bool" => "bool",
            "pointer" => "void *",
            "cstring" => "char *",
            _ => return None,
        }
        .to_string(),
    )
}

// ── Rust ───────────────────────────────────────────────────────────────────

/// `extern "C"` functions with an unmangled symbol: `#[no_mangle]` / `#[unsafe(no_mangle)]`,
/// `#[export_name = "…"]`, or equilibrium-rust's `#[ffi]` (which adds both). Used when
/// `cbindgen` is not installed; it covers primitive and pointer signatures.
fn rust_functions(source: &str) -> Vec<ForeignFn> {
    let text = strip_c_comments(source);
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    let mut unmangled = false;
    let mut ffi = false;
    let mut export_name = None;
    for (index, line) in lines.iter().enumerate() {
        let trimmed = line.trim();
        if trimmed.starts_with("#[") {
            let attr = trimmed.replace(' ', "");
            unmangled |= attr.contains("no_mangle");
            ffi |= attr == "#[ffi]" || attr.ends_with("::ffi]");
            if let Some(name) = attr.split("export_name=\"").nth(1) {
                export_name = name.split('"').next().map(str::to_string);
                unmangled = true;
            }
            continue;
        }
        if trimmed.is_empty() {
            continue;
        }
        let is_fn = trimmed.contains("fn ") && !trimmed.starts_with("//");
        if is_fn && ((unmangled && trimmed.contains("extern \"C\"")) || ffi) {
            let signature = signature_text(&lines, index, '{');
            if let Some(function) = rust_signature(&signature, export_name.take()) {
                out.push(function);
            }
        }
        unmangled = false;
        ffi = false;
        export_name = None;
    }
    out
}

fn rust_signature(signature: &str, export_name: Option<String>) -> Option<ForeignFn> {
    let after_fn = signature.split_once("fn ")?.1;
    let name_end = after_fn.find(|c: char| !(c.is_alphanumeric() || c == '_'))?;
    let (params, after) = parenthesized(after_fn)?;
    let mut parsed = Vec::new();
    for (index, param) in split_top_level_commas(params).into_iter().enumerate() {
        let param = param.trim();
        if param.is_empty() {
            continue;
        }
        let (pattern, ty) = param.split_once(':')?;
        let name = pattern.trim().trim_start_matches("mut ").trim();
        let name = if name.starts_with('_') || !crate::c_header::is_c_identifier(name) {
            format!("arg{index}")
        } else {
            name.to_string()
        };
        parsed.push((name, ty.trim().to_string()));
    }
    let ret = after
        .split("where")
        .next()
        .and_then(|head| head.trim().strip_prefix("->"))
        .map(|ty| ty.trim().to_string())
        .filter(|ty| ty != "()");
    Some(ForeignFn {
        symbol: export_name.unwrap_or_else(|| after_fn[..name_end].to_string()),
        params: parsed,
        ret,
    })
}

fn rust_type(ty: &str) -> Option<String> {
    let ty = ty.trim();
    if let Some(inner) = ty.strip_prefix("*const ") {
        return rust_pointee(inner).map(|c| pointer_to(&c, true));
    }
    if let Some(inner) = ty.strip_prefix("*mut ") {
        return rust_pointee(inner).map(|c| pointer_to(&c, false));
    }
    let ty = ["std::os::raw::", "core::ffi::", "std::ffi::", "libc::"]
        .iter()
        .find_map(|prefix| ty.strip_prefix(prefix))
        .unwrap_or(ty);
    Some(
        match ty {
            "i8" => "int8_t",
            "i16" => "int16_t",
            "i32" => "int32_t",
            "i64" => "int64_t",
            "u8" => "uint8_t",
            "u16" => "uint16_t",
            "u32" => "uint32_t",
            "u64" => "uint64_t",
            "isize" => "intptr_t",
            "usize" => "size_t",
            "f32" | "c_float" => "float",
            "f64" | "c_double" => "double",
            "bool" => "bool",
            "c_int" => "int",
            "c_uint" => "unsigned int",
            "c_long" => "long",
            "c_ulong" => "unsigned long",
            "c_longlong" => "long long",
            "c_ulonglong" => "unsigned long long",
            "c_short" => "short",
            "c_ushort" => "unsigned short",
            "c_char" => "char",
            "c_schar" => "signed char",
            "c_uchar" => "unsigned char",
            _ => return None,
        }
        .to_string(),
    )
}

/// A pointee may also be `c_void` or another pointer.
fn rust_pointee(ty: &str) -> Option<String> {
    let ty = ty.trim();
    if ty.ends_with("c_void") {
        return Some("void".to_string());
    }
    rust_type(ty)
}

// ── Zig ────────────────────────────────────────────────────────────────────

/// `export fn name(a: c_int) c_int {` (optionally `pub`, optionally `callconv(.c)`). Zig's own
/// `-femit-h` is accepted but writes nothing in current releases, so the source is read instead.
fn zig_functions(source: &str) -> Vec<ForeignFn> {
    let text = strip_c_comments(source);
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    for (index, line) in lines.iter().enumerate() {
        let trimmed = line.trim_start();
        let trimmed = trimmed.strip_prefix("pub ").unwrap_or(trimmed);
        let Some(rest) = trimmed.strip_prefix("export fn ") else {
            continue;
        };
        let name_end = rest
            .find(|c: char| !(c.is_alphanumeric() || c == '_'))
            .unwrap_or(rest.len());
        let signature = signature_text(&lines, index, '{');
        let Some((params, after)) = parenthesized(&signature) else {
            continue;
        };
        let Some(params) = named_params(params, &[], ":") else {
            continue;
        };
        let mut ret = after.trim().to_string();
        if let Some(at) = ret.find("callconv(") {
            let end = ret[at..]
                .find(')')
                .map_or(ret.len(), |close| at + close + 1);
            ret.replace_range(at..end, "");
        }
        let ret = ret.trim().to_string();
        out.push(ForeignFn {
            symbol: rest[..name_end].to_string(),
            params,
            ret: (!ret.is_empty() && ret != "void").then_some(ret),
        });
    }
    out
}

fn zig_type(ty: &str) -> Option<String> {
    let ty = ty.trim();
    let ty = ty.strip_prefix('?').unwrap_or(ty);
    for prefix in ["[*c]", "[*]", "*"] {
        if let Some(rest) = ty.strip_prefix(prefix) {
            let rest = rest.trim_start();
            let (is_const, pointee) = match rest.strip_prefix("const ") {
                Some(pointee) => (true, pointee),
                None => (false, rest),
            };
            let pointee = match pointee.trim() {
                "anyopaque" => "void".to_string(),
                other => zig_type(other)?,
            };
            return Some(pointer_to(&pointee, is_const));
        }
    }
    Some(
        match ty {
            "c_char" => "char",
            "c_short" => "short",
            "c_ushort" => "unsigned short",
            "c_int" => "int",
            "c_uint" => "unsigned int",
            "c_long" => "long",
            "c_ulong" => "unsigned long",
            "c_longlong" => "long long",
            "c_ulonglong" => "unsigned long long",
            "i8" => "int8_t",
            "i16" => "int16_t",
            "i32" => "int32_t",
            "i64" => "int64_t",
            "u8" => "uint8_t",
            "u16" => "uint16_t",
            "u32" => "uint32_t",
            "u64" => "uint64_t",
            "isize" => "intptr_t",
            "usize" => "size_t",
            "f32" => "float",
            "f64" => "double",
            "bool" => "bool",
            _ => return None,
        }
        .to_string(),
    )
}

// ── Odin ───────────────────────────────────────────────────────────────────

/// `@(export) name :: proc "c" (a, b: c.int) -> c.int {`, with `link_name="…"` renaming the
/// symbol. Only the `"c"`/`"cdecl"` calling conventions are C ABI; Odin's default convention
/// passes an implicit context and is skipped.
fn odin_functions(source: &str) -> Vec<ForeignFn> {
    let text = strip_c_comments(source);
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    let mut exported = false;
    let mut link_name = None;
    for (index, line) in lines.iter().enumerate() {
        let mut trimmed = line.trim();
        while let Some(attr) = trimmed.strip_prefix('@') {
            let (body, rest) = match attr.strip_prefix('(') {
                Some(inner) => inner.split_once(')').unwrap_or((inner, "")),
                None => attr.split_once(char::is_whitespace).unwrap_or((attr, "")),
            };
            let body = body.replace(' ', "");
            exported |= body.split(',').any(|item| item == "export");
            if let Some(name) = body.split("link_name=\"").nth(1) {
                link_name = name.split('"').next().map(str::to_string);
            }
            trimmed = rest.trim_start();
        }
        if trimmed.is_empty() {
            continue;
        }
        if let Some((name, rest)) = trimmed.split_once("::") {
            let rest = rest.trim_start();
            let convention = rest
                .strip_prefix("proc")
                .map(str::trim_start)
                .and_then(|after| after.strip_prefix('"'))
                .and_then(|after| after.split('"').next());
            if exported && matches!(convention, Some("c" | "cdecl")) {
                let signature = signature_text(&lines, index, '{');
                let after_proc = signature.split_once("proc").map_or("", |(_, rest)| rest);
                if let Some((params, after)) = parenthesized(after_proc) {
                    if let Some(params) = named_params(params, &[], ":") {
                        let ret = after
                            .trim()
                            .strip_prefix("->")
                            .map(|ty| ty.trim().to_string())
                            .filter(|ty| !ty.is_empty());
                        out.push(ForeignFn {
                            symbol: link_name.take().unwrap_or_else(|| name.trim().to_string()),
                            params,
                            ret,
                        });
                    }
                }
            }
        }
        exported = false;
        link_name = None;
    }
    out
}

fn odin_type(ty: &str) -> Option<String> {
    let ty = ty.trim();
    if let Some(inner) = ty.strip_prefix("[^]").or_else(|| ty.strip_prefix('^')) {
        return odin_type(inner).map(|c| pointer_to(&c, false));
    }
    let c_name = ty.strip_prefix("c.");
    if let Some(name) = c_name {
        let mapped = match name {
            "int" | "uint" | "long" | "ulong" | "short" | "ushort" | "char" | "float"
            | "double" | "size_t" | "ssize_t" | "bool" => name
                .replace("uint", "unsigned int")
                .replace("ulong", "unsigned long")
                .replace("ushort", "unsigned short")
                .replace("ssize_t", "ptrdiff_t"),
            "longlong" => "long long".to_string(),
            "ulonglong" => "unsigned long long".to_string(),
            "schar" => "signed char".to_string(),
            "uchar" => "unsigned char".to_string(),
            other if other.ends_with("_t") && other.contains("int") => other.to_string(),
            _ => return None,
        };
        return Some(mapped);
    }
    Some(
        match ty {
            "i8" => "int8_t",
            "i16" => "int16_t",
            "i32" => "int32_t",
            "i64" => "int64_t",
            "u8" => "uint8_t",
            "u16" => "uint16_t",
            "u32" => "uint32_t",
            "u64" => "uint64_t",
            "int" => "intptr_t",
            "uint" | "uintptr" => "uintptr_t",
            "f32" => "float",
            "f64" => "double",
            "bool" | "b8" => "bool",
            "rawptr" => "void *",
            "cstring" => "char *",
            _ => return None,
        }
        .to_string(),
    )
}

// ── V ──────────────────────────────────────────────────────────────────────

/// `@[export: 'name']` (or the older `[export: 'name']`) on a following `fn`; the attribute
/// names the C symbol.
fn v_functions(source: &str) -> Vec<ForeignFn> {
    let text = strip_c_comments(source);
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    let mut symbol: Option<String> = None;
    for (index, line) in lines.iter().enumerate() {
        let trimmed = line.trim();
        let attr = trimmed
            .strip_prefix("@[")
            .or_else(|| trimmed.strip_prefix('['));
        if let Some(attr) = attr.filter(|attr| attr.trim_start().starts_with("export")) {
            symbol = attr
                .split(['\'', '"'])
                .nth(1)
                .map(str::to_string)
                .filter(|name| !name.is_empty());
            continue;
        }
        if trimmed.is_empty() {
            continue;
        }
        let declaration = trimmed.strip_prefix("pub ").unwrap_or(trimmed);
        if let (Some(name), true) = (symbol.take(), declaration.starts_with("fn ")) {
            let signature = signature_text(&lines, index, '{');
            if let Some((params, after)) = parenthesized(&signature) {
                if let Some(params) = named_params(params, &[], " ") {
                    let ret = after.trim().to_string();
                    out.push(ForeignFn {
                        symbol: name,
                        params,
                        ret: (!ret.is_empty()).then_some(ret),
                    });
                }
            }
        }
        symbol = None;
    }
    out
}

fn v_type(ty: &str) -> Option<String> {
    let ty = ty.trim();
    if let Some(inner) = ty.strip_prefix('&') {
        return v_type(inner).map(|c| pointer_to(&c, false));
    }
    Some(
        match ty {
            "int" | "i32" => "int32_t",
            "i8" => "int8_t",
            "i16" => "int16_t",
            "i64" => "int64_t",
            "u8" | "byte" => "uint8_t",
            "u16" => "uint16_t",
            "u32" => "uint32_t",
            "u64" => "uint64_t",
            "isize" => "intptr_t",
            "usize" => "size_t",
            "f32" => "float",
            "f64" => "double",
            "bool" => "bool",
            "voidptr" => "void *",
            "charptr" => "char *",
            "byteptr" => "uint8_t *",
            _ => return None,
        }
        .to_string(),
    )
}

