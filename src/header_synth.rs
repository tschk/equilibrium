//! Synthesize a C header from a source file's exported functions, for languages whose compiler
//! does not write a usable one. Each language contributes a thin scanner that finds exported
//! functions and a type map from its spelling of a type to a C type; this module does the rest
//! (grouped parameters, pointers, rendering, and reporting what could not be mapped).

use crate::c_header::{parse_function_line, strip_c_comments};
use crate::detector::Language;

/// An exported function as the source language spells it.
pub(crate) struct ForeignFn {
    /// The C symbol name.
    pub(crate) symbol: String,
    /// `(name, type)` in source spelling.
    pub(crate) params: Vec<(String, String)>,
    /// `None` means the function returns nothing (`void`).
    pub(crate) ret: Option<String>,
}

pub(crate) struct Synthesized {
    pub(crate) header: String,
    pub(crate) warnings: Vec<String>,
}

/// A language's mapping from its type spelling to a C type, or `None` when it has no C equivalent.
type TypeMap = fn(&str) -> Option<String>;

/// Build a header for `source` written in `language`, or `None` when this language has no
/// source scanner or the source exports nothing that could be bound.
pub(crate) fn synthesize(language: Language, source: &str) -> Option<Synthesized> {
    let (functions, map, prelude): (Vec<ForeignFn>, TypeMap, String) = match language {
        Language::C => (c_functions(source), c_type, c_type_declarations(source)),
        Language::Cpp => (c_functions(&extern_c_items(source)), c_type, String::new()),
        _ => return None,
    };
    render(language, functions, map, &prelude)
}

fn render(
    language: Language,
    functions: Vec<ForeignFn>,
    map: TypeMap,
    prelude: &str,
) -> Option<Synthesized> {
    let mut warnings = Vec::new();
    let mut prototypes = Vec::new();
    'functions: for function in functions {
        let ret = match &function.ret {
            None => "void".to_string(),
            Some(ty) => match map(ty) {
                Some(c) => c,
                None => {
                    warnings.push(unmapped(language, &function.symbol, "return type", ty));
                    continue;
                }
            },
        };
        let mut params = Vec::new();
        for (name, ty) in &function.params {
            match map(ty) {
                Some(c) if c != "void" => params.push(format!("{c} {name}")),
                _ => {
                    warnings.push(unmapped(language, &function.symbol, "parameter", ty));
                    continue 'functions;
                }
            }
        }
        let params = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        prototypes.push(format!("{ret} {}({params});", function.symbol));
    }
    if prototypes.is_empty() {
        return None;
    }
    let mut header = format!(
        "/* Generated by equilibrium-ffi from {language:?} source exports. */\n\
         #pragma once\n#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n"
    );
    if !prelude.trim().is_empty() {
        header.push_str(prelude.trim());
        header.push_str("\n\n");
    }
    for prototype in prototypes {
        header.push_str(&prototype);
        header.push('\n');
    }
    Some(Synthesized { header, warnings })
}

fn unmapped(language: Language, symbol: &str, what: &str, ty: &str) -> String {
    format!("Skipped export {symbol}: {language:?} {what} type `{ty}` has no C equivalent")
}

// ── C ──────────────────────────────────────────────────────────────────────

/// C types are already C; the binding generator reports any it cannot map.
fn c_type(ty: &str) -> Option<String> {
    Some(ty.to_string())
}

/// Split C source into its top-level items: `(head, body)` where `head` is the text before a
/// depth-0 `{` (or the whole `;`-terminated item) and `body` is the braced block, if any.
/// Preprocessor lines are dropped; callers that need them read them separately.
fn top_level_items(source: &str) -> Vec<(String, Option<String>)> {
    let text: String = strip_c_comments(source)
        .lines()
        .filter(|line| !line.trim_start().starts_with('#'))
        .collect::<Vec<_>>()
        .join("\n");
    let mut items = Vec::new();
    let mut depth = 0usize;
    let mut head = String::new();
    let mut body = String::new();
    for ch in text.chars() {
        match ch {
            '{' => {
                if depth > 0 {
                    body.push(ch);
                }
                depth += 1;
            }
            '}' => {
                depth = depth.saturating_sub(1);
                if depth > 0 {
                    body.push(ch);
                } else {
                    items.push((head.trim().to_string(), Some(std::mem::take(&mut body))));
                    head.clear();
                }
            }
            ';' if depth == 0 => {
                let item = head.trim().to_string();
                head.clear();
                // `typedef struct {..} T;` — the name after `}` belongs to the previous item.
                if let Some((prev_head, Some(_))) = items.last_mut() {
                    if prev_head.starts_with("typedef") || is_aggregate(prev_head) {
                        prev_head.push_str(" } ");
                        prev_head.push_str(&item);
                        continue;
                    }
                }
                if !item.is_empty() {
                    items.push((item, None));
                }
            }
            _ if depth > 0 => body.push(ch),
            _ => head.push(ch),
        }
    }
    items
}

fn is_aggregate(head: &str) -> bool {
    ["struct", "union", "enum"]
        .iter()
        .any(|kw| head.split_whitespace().next() == Some(kw))
}

/// Non-`static` function definitions, as prototypes. `main` is never part of a library ABI.
fn c_functions(source: &str) -> Vec<ForeignFn> {
    top_level_items(source)
        .into_iter()
        .filter_map(|(head, body)| {
            body?;
            let words: Vec<&str> = head.split_whitespace().collect();
            if words.contains(&"static") || words.first() == Some(&"typedef") || is_aggregate(&head)
            {
                return None;
            }
            if !head.contains('(') || head.contains('=') {
                return None;
            }
            let head = head.replace("inline ", "").replace("extern ", "");
            let def = parse_function_line(&format!("{} ;", head.trim()))?;
            (def.name != "main").then(|| ForeignFn {
                symbol: def.name,
                params: def
                    .params
                    .into_iter()
                    .map(|(ty, name)| (name, ty))
                    .collect(),
                ret: (def.return_type.trim() != "void").then_some(def.return_type),
            })
        })
        .collect()
}

/// The type declarations a prototype may reference: top-level typedefs, aggregates and enums,
/// copied verbatim, plus `#include <...>` and object-like `#define`s.
fn c_type_declarations(source: &str) -> String {
    let mut out = Vec::new();
    for line in strip_c_comments(source).lines() {
        let line = line.trim();
        let directive = line.trim_start_matches('#').trim_start();
        if line.starts_with('#')
            && (directive.starts_with("include <")
                || (directive.starts_with("define ")
                    && !directive["define ".len()..]
                        .split_whitespace()
                        .next()
                        .is_some_and(|name| name.contains('('))))
        {
            out.push(line.to_string());
        }
    }
    for (head, body) in top_level_items(source) {
        let typedef = head.starts_with("typedef");
        if !typedef && !is_aggregate(&head) {
            continue;
        }
        match body {
            // `typedef struct P {` + body + ` } P` were stitched into `head` as "<open> } <name>".
            Some(body) => match head.split_once(" } ") {
                Some((open, name)) => out.push(format!("{open} {{{body}}} {name};")),
                None if !head.contains('(') => out.push(format!("{head} {{{body}}};")),
                None => {}
            },
            None => out.push(format!("{head};")),
        }
    }
    out.join("\n")
}

// ── C++ ────────────────────────────────────────────────────────────────────

/// The `extern "C"` part of a C++ source, as C: the contents of `extern "C" { … }` blocks and
/// each `extern "C" <definition>`. Everything else is C++ and has no C ABI.
fn extern_c_items(source: &str) -> String {
    let text = strip_c_comments(source);
    let mut out = String::new();
    let mut rest = text.as_str();
    while let Some(at) = rest.find("extern \"C\"") {
        rest = rest[at + "extern \"C\"".len()..].trim_start();
        let block = rest.starts_with('{');
        let start = usize::from(block);
        let mut depth = 0usize;
        let mut end = rest.len();
        for (index, ch) in rest.char_indices().skip(start) {
            match ch {
                '{' => depth += 1,
                '}' if depth == 0 && block => {
                    end = index;
                    break;
                }
                '}' => {
                    depth -= 1;
                    if depth == 0 && !block {
                        end = index + 1;
                        break;
                    }
                }
                ';' if depth == 0 && !block => {
                    end = index + 1;
                    break;
                }
                _ => {}
            }
        }
        out.push_str(&rest[start..end]);
        out.push('\n');
        rest = &rest[(end + usize::from(block)).min(rest.len())..];
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn c_header_keeps_public_definitions_and_their_types() {
        let source = r#"
#include <stdint.h>
#define LIMIT 8
#define SQUARE(x) ((x) * (x))
typedef struct Point { int x; int y; } Point;
static int helper(int a) { return a; }
int main(void) { return 0; }
uint32_t mix(uint32_t a,
             uint32_t b) {
    return a ^ b;
}
Point origin(void) { Point p = {0, 0}; return p; }
const char *label(int, double) { return "x"; }
"#;
        let out = synthesize(Language::C, source).expect("header");
        let h = &out.header;
        assert!(h.contains("#include <stdint.h>"), "{h}");
        assert!(h.contains("#define LIMIT 8"), "{h}");
        assert!(!h.contains("SQUARE"), "{h}");
        assert!(
            h.contains("typedef struct Point { int x; int y; } Point;"),
            "{h}"
        );
        assert!(h.contains("uint32_t mix(uint32_t a, uint32_t b);"), "{h}");
        assert!(h.contains("Point origin(void);"), "{h}");
        assert!(
            h.contains("const char * label(int arg0, double arg1);"),
            "{h}"
        );
        assert!(!h.contains("helper"), "{h}");
        assert!(!h.contains("main"), "{h}");
    }

    #[test]
    fn cpp_header_keeps_only_extern_c_definitions() {
        let source = r#"
#include <string>
class Counter { public: int add(int a, int b) { return a + b; } };
int mangled(int a) { return a; }
extern "C" int single(int a, int b) { Counter c; return c.add(a, b); }
extern "C" {
    double scale(double v, int times) { return v * times; }
    static int hidden(int a) { return a; }
}
"#;
        let h = synthesize(Language::Cpp, source).expect("header").header;
        assert!(h.contains("int single(int a, int b);"), "{h}");
        assert!(h.contains("double scale(double v, int times);"), "{h}");
        for absent in ["mangled", "hidden", "Counter", "#include <string>"] {
            assert!(!h.contains(absent), "{absent} leaked into:\n{h}");
        }
    }
}
